export let currentLang: Lang = 'en';

export function applyLang(lang: Lang): void {
  currentLang = lang;
  const isTouch = window.matchMedia('(hover: none)').matches;
  document.documentElement.lang = lang === 'ca' ? 'ca' : lang === 'es' ? 'es' : 'en';

  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n!;
    const trans = i18n[lang];
    const touchKey = key + '_touch';
    const value = (isTouch && trans[touchKey]) ? trans[touchKey] : trans[key];
    if (value !== undefined) el.innerHTML = value;
  });

  document.querySelectorAll<HTMLButtonElement>('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });

  // Signal section components to re-render with new language
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}
